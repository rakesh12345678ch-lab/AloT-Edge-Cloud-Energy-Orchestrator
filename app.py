import hashlib
import json
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd
import streamlit as st

APP_TITLE = "IIoT Orchestrator | SME Energy SCADA"
DATA_DIR = Path("data")
DATA_DIR.mkdir(exist_ok=True)
CSV_FILE = DATA_DIR / "telemetry.csv"
HASH_FILE = DATA_DIR / "telemetry_sha256.txt"

st.set_page_config(page_title=APP_TITLE, layout="wide")
st.title("IIoT Orchestrator for SME Energy Optimisation")
st.caption("Software prototype • simulated telemetry • not connected to live electrical equipment")

# -------------------- Operator settings --------------------
with st.sidebar:
    st.header("Plant settings")





    off_peak_rate = st.number_input("Off-peak tariff (■/kWh)", 0.0, 100.0, 5.0, 0.1)
    peak_rate = st.number_input("Peak tariff (■/kWh)", 0.0, 200.0, 9.0, 0.1)
    peak_start = st.slider("Peak start hour", 0, 23, 14)
    peak_end = st.slider("Peak end hour", 0, 23, 22)
    md_limit = st.number_input("Maximum demand limit (kW)", 1.0, 1000.0, 12.0, 0.5)
    md_penalty = st.number_input("MD penalty (■/kW)", 0.0, 10000.0, 300.0, 10.0)
    ghg_factor = st.number_input("Grid emission factor (kg CO■/kWh)", 0.0, 3.0, 0.70, 0.01)
    production_units = st.number_input("Production units in this period", 1, 100000, 100)
    simulate_button = st.button("Generate new telemetry", type="primary")

# -------------------- Telemetry model --------------------
def generate_telemetry():
    """Create plausible demo values. Replace this function with real device drivers."""
    now = datetime.now()
    rng = np.random.default_rng()
    voltage = float(rng.normal(230.0, 1.8))
    frequency = float(rng.normal(50.0, 0.04))
    pf = float(np.clip(rng.normal(0.91, 0.025), 0.70, 0.99))

    motor_kw = float(rng.uniform(2.0, 4.0))
    thermal_kw = float(rng.uniform(1.5, 3.0))
    auxiliary_kw = float(rng.uniform(0.3, 0.8))
    base_kw = float(rng.uniform(1.0, 1.8))
    total_kw = motor_kw + thermal_kw + auxiliary_kw + base_kw

    # Single-phase illustrative current estimate. Actual 3-phase calculations
    # require the correct line/phase voltage, PF and wiring configuration.
    current = total_kw * 1000.0 / max(voltage * pf, 1.0)
    kva = total_kw / max(pf, 0.01)
    kvar = float(np.sqrt(max(kva * kva - total_kw * total_kw, 0.0)))

    return {
        "timestamp": now.isoformat(timespec="seconds"),
        "voltage_v": round(voltage, 2),
        "current_a": round(current, 2),
        "frequency_hz": round(frequency, 3),
        "power_factor": round(pf, 3),
        "active_power_kw": round(total_kw, 3),
        "apparent_power_kva": round(kva, 3),
        "reactive_power_kvar": round(kvar, 3),
        "motor_kw": round(motor_kw, 3),
        "thermal_kw": round(thermal_kw, 3),
        "auxiliary_kw": round(auxiliary_kw, 3),
        "base_kw": round(base_kw, 3),
        "source": "SIMULATED"
    }

if "reading" not in st.session_state or simulate_button:
    st.session_state.reading = generate_telemetry()

reading = st.session_state.reading
hour = datetime.fromisoformat(reading["timestamp"]).hour
is_peak = peak_start <= hour < peak_end if peak_start < peak_end else (hour >= peak_start or hour < peak_end)
tariff = peak_rate if is_peak else off_peak_rate

# -------------------- Energy and financial calculations --------------------
# This demo assumes the displayed reading represents a one-hour interval.
# For real telemetry, integrate measured kW over actual elapsed time.
energy_kwh = reading["active_power_kw"] * 1.0
energy_cost = energy_kwh * tariff
scope2_kg = energy_kwh * ghg_factor
sec = energy_kwh / max(production_units, 1)
md_excess_kw = max(reading["active_power_kw"] - md_limit, 0.0)
estimated_md_penalty = md_excess_kw * md_penalty

# Peak-shaving advice: never automatically stop a critical production motor.
recommended_action = "No action required"
recommended_saving_kw = 0.0
if reading["active_power_kw"] > md_limit and reading["auxiliary_kw"] > 0:
    recommended_action = "Consider shedding the non-critical auxiliary load"
    recommended_saving_kw = reading["auxiliary_kw"]

# -------------------- Dashboard --------------------
st.subheader("Live electrical telemetry")
st.info("DEMO MODE: values are generated by software and are not actual meter readings.")
c1, c2, c3, c4 = st.columns(4)
c1.metric("Voltage", f'{reading["voltage_v"]:.1f} V')
c2.metric("Current (estimated)", f'{reading["current_a"]:.1f} A')
c3.metric("Frequency", f'{reading["frequency_hz"]:.2f} Hz')
c4.metric("Power factor", f'{reading["power_factor"]:.3f}')

c5, c6, c7, c8 = st.columns(4)
c5.metric("Active power", f'{reading["active_power_kw"]:.2f} kW')
c6.metric("Apparent power", f'{reading["apparent_power_kva"]:.2f} kVA')
c7.metric("Reactive power", f'{reading["reactive_power_kvar"]:.2f} kVAr')
c8.metric("Tariff period", "PEAK" if is_peak else "OFF-PEAK")

st.subheader("Load-centre breakdown")
loads = pd.DataFrame({
    "Load": ["Motor process (LC-1)", "Thermal process (LC-2)",
             "Auxiliary load", "Base load"],





    "Power (kW)": [reading["motor_kw"], reading["thermal_kw"],
                   reading["auxiliary_kw"], reading["base_kw"]]
})
st.bar_chart(loads.set_index("Load"))
st.dataframe(loads, use_container_width=True, hide_index=True)

st.subheader("Energy, cost and carbon indicators")
a, b, c, d = st.columns(4)
a.metric("Energy (1-hour demo interval)", f"{energy_kwh:.2f} kWh")
b.metric("Estimated energy cost", f"■{energy_cost:.2f}")
c.metric("Scope-2 emissions", f"{scope2_kg:.2f} kg CO■e")
d.metric("Specific energy consumption", f"{sec:.4f} kWh/unit")

st.subheader("Demand management")
st.write(f"Configured maximum demand: **{md_limit:.2f} kW**")
st.write(f"Current simulated demand: **{reading['active_power_kw']:.2f} kW**")
st.write(f"Estimated demand penalty for this sample: **■{estimated_md_penalty:.2f}**")
if recommended_saving_kw > 0:
    st.warning(f"{recommended_action}. Potential reduction: {recommended_saving_kw:.2f} kW.")
else:
    st.success(recommended_action)
st.caption("This is an advisory calculation only. Do not connect it directly to motor/SSR outputs.")

# -------------------- History, export and integrity --------------------
row = {**reading, "tariff_rupees_per_kwh": tariff,
       "energy_kwh": energy_kwh, "energy_cost_rupees": energy_cost,
       "scope2_kg_co2e": scope2_kg, "sec_kwh_per_unit": sec,
       "md_excess_kw": md_excess_kw, "recommended_action": recommended_action}

if CSV_FILE.exists():
    history = pd.read_csv(CSV_FILE)
else:
    history = pd.DataFrame()

if st.button("Save current sample to history"):
    history = pd.concat([history, pd.DataFrame([row])], ignore_index=True)
    history.to_csv(CSV_FILE, index=False)
    st.success("Sample saved to data/telemetry.csv")

if CSV_FILE.exists():
    history = pd.read_csv(CSV_FILE)
    st.subheader("Saved telemetry history")
    st.dataframe(history.tail(20), use_container_width=True)
    st.download_button("Download telemetry CSV",
        data=history.to_csv(index=False).encode("utf-8"),
        file_name="sme_telemetry.csv", mime="text/csv")

if st.button("Create SHA-256 audit hash"):
    payload = json.dumps(row, sort_keys=True, separators=(",", ":")).encode("utf-8")
    digest = hashlib.sha256(payload).hexdigest()
    HASH_FILE.write_text(
        f"Timestamp: {reading['timestamp']}\nSHA256: {digest}\n",
        encoding="utf-8"
    )
    st.code(digest)
    st.success("Hash written to data/telemetry_sha256.txt")

st.caption("Prototype note: the hash proves the integrity of this exported sample only if the original "
              "payload and hash are retained securely. It is not, by itself, a complete ESG verification system.")
